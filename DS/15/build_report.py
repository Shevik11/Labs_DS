def chart(values, labels, title, number, unit):
    drawing=Drawing(500,185)
    scale=330/max(values)
    for i,(value,label) in enumerate(zip(values,labels)):
        y=140-i*33
        drawing.add(String(0,y+4,label,fontName='TNR',fontSize=12,fillColor=colors.black))
        drawing.add(Rect(100,y,max(1,value*scale),18,fillColor=colors.HexColor('#777777'),strokeColor=None))
        drawing.add(String(105+value*scale,y+3,f'{value:.1f}',fontName='TNR',fontSize=12))
    drawing.add(String(100,5,unit,fontName='TNR',fontSize=12))
    story.append(KeepTogether([drawing,para(f'Рис. {number} - {title}',caption)]))

