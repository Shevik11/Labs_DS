def listing(path):
    lines=[]
    for line in (R/path).read_text('utf-8-sig').expandtabs(4).splitlines():
        lines.extend(textwrap.wrap(line, width=68, replace_whitespace=False,
            drop_whitespace=False,break_long_words=True,break_on_hyphens=False) or [''])
    # Small contiguous chunks permit clean page breaks with a shaded listing.
    for i in range(0,len(lines),32):
        t=Table([[Preformatted('\n'.join(lines[i:i+32]),code)]],colWidths=[178*mm])
        t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,-1),colors.HexColor('#F2F2F2')),
            ('BOX',(0,0),(-1,-1),.5,colors.HexColor('#D9D9D9')),
            ('LEFTPADDING',(0,0),(-1,-1),7),('RIGHTPADDING',(0,0),(-1,-1),7),
            ('TOPPADDING',(0,0),(-1,-1),5),('BOTTOMPADDING',(0,0),(-1,-1),5)]))
